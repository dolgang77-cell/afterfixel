        return $today->dayOfWeek === $weekday
            ? $today
            : $today->next($weekday);
    }

    private static function templateBaseDate(CarbonImmutable $today, array $template): CarbonImmutable
    {
        if (!empty($template['start_date'])) {
            $startDate = CarbonImmutable::parse($template['start_date']);

            if ($startDate->gt($today)) {
                return $startDate;
            }
        }

        return $today;
    }

    private static function buildPartyRecord(array $template, CarbonImmutable $date, int $clubId): array
    {
        return [
            'club_id' => $clubId,
            'name' => $template['name'],
            'slug' => $template['slug_prefix'] . '-' . $date->format('Ymd'),
            'event_date' => $date->toDateString(),
            'start_time' => $template['start_time'],
            'end_time' => $template['end_time'],
            'lineup' => $template['lineup'],
            'ticket_price_min' => $template['ticket_price_min'],
            'ticket_price_max' => $template['ticket_price_max'],
            'genre' => $template['genre'],
            'tags' => $template['tags'],
            'dress_code' => $template['dress_code'],
            'entry_condition' => $template['entry_condition'],
            'description' => $template['description'],
            'thumbnail' => $template['thumbnail'],
            'status' => 'upcoming',
        ];
    }
