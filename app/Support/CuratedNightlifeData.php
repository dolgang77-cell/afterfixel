    public static function partyRecords(CarbonImmutable $today, array $clubIds): array
    {
        $records = [];
        $specialPartyDateKeys = collect(self::specialParties())
            ->map(function (array $template): string {
                return $template['club_slug'].'@'.$template['event_date'];
            })
            ->flip();

        foreach (self::rollingPartyTemplates() as $template) {
            $clubId = $clubIds[$template['club_slug']] ?? null;

            if (!$clubId) {
                continue;
            }

            $date = self::nextOrSameWeekday(self::templateBaseDate($today, $template), $template['weekday']);

            if ($specialPartyDateKeys->has($template['club_slug'].'@'.$date->toDateString())) {
                continue;
            }

            $records[] = self::buildPartyRecord($template, $date, $clubId);
        }

        foreach (self::specialParties() as $template) {
            $clubId = $clubIds[$template['club_slug']] ?? null;

            if (!$clubId) {
                continue;
            }

            $date = CarbonImmutable::parse($template['event_date']);

            if ($date->lt($today)) {
                continue;
            }

            $records[] = self::buildPartyRecord($template, $date, $clubId);
        }

        return $records;
    }

